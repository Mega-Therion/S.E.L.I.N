/// The checks named by a report's `rejection_reason`, in order.
fn refused_by(reason: Option<&str>) -> Vec<&'static str> {
    reason.map_or_else(Vec::new, |reason| {
        reason
            .split(" | ")
            .map(|part| {
                let tag = part.split(':').next().unwrap_or_default();
                TAGS.iter()
                    .find(|(t, _)| *t == tag)
                    .map_or("unknown", |(_, check)| check)
            })
            .collect()
    })
}

fn signal_name(signal: GateSignal) -> &'static str {
    match signal {
        GateSignal::Execute => "execute",
        GateSignal::Suspend => "suspend",
        GateSignal::Abort => "abort",
    }
}

/// A double as the vector file writes it: the shortest round-trip decimal, or NaN / ±Infinity.
fn number(x: f64) -> String {
    if x.is_nan() {
        "NaN".to_string()
    } else if x.is_infinite() {
        if x > 0.0 { "Infinity" } else { "-Infinity" }.to_string()
    } else {
        format!("{x:?}")
    }
}

fn json(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

fn main() {
    let rows = rows();
    let mut wrong = Vec::new();
    let mut lines = Vec::new();
    let mut ids = std::collections::HashSet::new();
    for r in &rows {
        if !ids.insert(r.id) {
            wrong.push(format!("{}: duplicate id", r.id));
        }
        let gate = r.threshold.map_or_else(AdcclGate::default, AdcclGate::new);
        let report = gate.evaluate(r.v, r.j);
        let got = refused_by(report.rejection_reason.as_deref());
        let domain_text_ok = (r.refused_by == ["domain"])
            == (report.rejection_reason.as_deref() == Some(DOMAIN_REFUSAL));
        if report.signal != r.signal
            || got.as_slice() != r.refused_by
            || report.passed != (r.signal == EXECUTE)
            || report.passed != report.rejection_reason.is_none()
            || !domain_text_ok
        {
            wrong.push(format!(
                "{}: the kernel says {:?} {:?}, the row says {:?} {:?}",
                r.id, report.signal, got, r.signal, r.refused_by
            ));
        }
        let checks: Vec<String> = r.refused_by.iter().map(|c| json(c)).collect();
        lines.push(format!(
            "    {{\"id\": {}, \"v\": {}, \"j\": {}, \"threshold\": {}, \"expect\": {{\"signal\": {}, \"passed\": {}, \"refused_by\": [{}], \"chi\": {}, \"mirror_chi\": {}}}, \"note\": {}}}",
            json(r.id),
            json(&number(r.v)),
            json(&number(r.j)),
            r.threshold.map_or_else(|| "null".to_string(), |t| json(&number(t))),
            json(signal_name(r.signal)),
            r.signal == EXECUTE,
            checks.join(", "),
            json(&number(report.chiral_invariant)),
            json(&number(report.mirror_chi)),
            json(&r.note),
        ));
    }
    if !wrong.is_empty() {
        eprintln!(
            "not written: the kernel disagrees with {} of {} rows",
            wrong.len(),
            rows.len()
        );
        for w in &wrong {
            eprintln!("  {w}");
        }
        std::process::exit(1);
    }

    let contract: Vec<String> = CONTRACT
        .iter()
        .map(|c| format!("    {}", json(c)))
        .collect();
    let tags: Vec<String> = TAGS
        .iter()
        .map(|(tag, check)| format!("{}: {}", json(tag), json(check)))
        .collect();
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str("  \"format\": \"selin-gate-conformance\",\n");
    out.push_str("  \"version\": 1,\n");
    out.push_str("  \"generator\": \"cargo run -q --locked -p archon_kernel --example selin_gate_vectors\",\n");
    out.push_str("  \"consumers\": [\"archon_kernel/tests/gate_conformance.rs\", \"test/gate_vectors.test.mjs\"],\n");
    out.push_str(&format!(
        "  \"contract\": [\n{}\n  ],\n",
        contract.join(",\n")
    ));
    out.push_str(&format!("  \"encoding\": {},\n", json(ENCODING)));
    out.push_str(&format!(
        "  \"constants\": {{\"chiral_floor\": {}, \"sovereign_ceiling\": {}, \"mirror_gap_min\": {}}},\n",
        json(&number(CHIRAL_FLOOR)),
        json(&number(SOVEREIGN_CEILING)),
        json(&number(MIRROR_GAP_MIN)),
    ));
    out.push_str(&format!(
        "  \"domain_refusal\": {},\n",
        json(DOMAIN_REFUSAL)
    ));
    out.push_str(&format!("  \"tags\": {{{}}},\n", tags.join(", ")));
    out.push_str(&format!("  \"rows\": [\n{}\n  ]\n", lines.join(",\n")));
    out.push_str("}\n");
    serde_json::from_str::<serde_json::Value>(&out).expect("the vector file is valid JSON");
    print!("{out}");
}
