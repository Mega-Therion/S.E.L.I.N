        for x in [
            compute_chiral_invariant(MIRROR_V, j),
            mirror_chi(MIRROR_V, j),
        ] {
            assert!(
                (0.5..1.0).contains(&x),
                "chi and mirror_chi at V = 0.72 stay in [0.5, 1): {x:?} at J = {j:?}"
            );
        }
