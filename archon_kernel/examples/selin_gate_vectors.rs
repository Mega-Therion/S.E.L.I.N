    let (j_passed_again, passed_steps) = next_where(j_refused_again, clears_mirror);
    let passed_steps = refused_steps + passed_steps;
    let gap_pass = gap(MIRROR_V, j_pass);
    let gap_refuse = gap(MIRROR_V, j_refuse);
    let gap_refused_again = gap(MIRROR_V, j_refused_again);
    let gap_passed_again = gap(MIRROR_V, j_passed_again);

