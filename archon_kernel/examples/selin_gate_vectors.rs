    // rises, so their values at the two ends bound them: they stay in [0.5, 1). There a double is
    // a multiple of 2^-53 and the difference of two of them is exact (Sterbenz), so every gap is
    // a multiple of 2^-53. The double 0.15 is not one, so no gap equals 0.15.
